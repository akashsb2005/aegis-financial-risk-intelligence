-- AEGIS market and evidence foundation.
-- Apply after database/ddl/01_schema.sql. Safe to apply repeatedly.
BEGIN;

CREATE TABLE IF NOT EXISTS public.securities (
    security_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL REFERENCES public.companies(company_id) ON DELETE CASCADE,
    ticker VARCHAR(32) NOT NULL,
    exchange VARCHAR(32) NOT NULL,
    asset_type VARCHAR(24) NOT NULL DEFAULT 'EQUITY',
    currency CHAR(3) NOT NULL DEFAULT 'USD',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_securities_exchange_ticker UNIQUE (exchange, ticker),
    CONSTRAINT chk_security_asset_type CHECK (asset_type IN ('EQUITY','ETF','INDEX')),
    CONSTRAINT chk_security_ticker_nonempty CHECK (length(trim(ticker)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_securities_company ON public.securities(company_id);

CREATE TABLE IF NOT EXISTS public.market_observations (
    observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    security_id BIGINT NOT NULL REFERENCES public.securities(security_id) ON DELETE CASCADE,
    observation_date DATE NOT NULL,
    open NUMERIC(20,6),
    high NUMERIC(20,6),
    low NUMERIC(20,6),
    close NUMERIC(20,6) NOT NULL,
    adjusted_close NUMERIC(20,6),
    volume BIGINT,
    source VARCHAR(40) NOT NULL DEFAULT 'yfinance',
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_market_observation UNIQUE (security_id, observation_date),
    CONSTRAINT chk_market_prices_nonnegative CHECK (
      close >= 0 AND (open IS NULL OR open >= 0) AND
      (high IS NULL OR high >= 0) AND (low IS NULL OR low >= 0) AND
      (adjusted_close IS NULL OR adjusted_close >= 0)),
    CONSTRAINT chk_market_ohlc_range CHECK (
      (high IS NULL OR low IS NULL OR high >= low) AND
      (high IS NULL OR high >= close) AND (low IS NULL OR low <= close) AND
      (open IS NULL OR high IS NULL OR high >= open) AND
      (open IS NULL OR low IS NULL OR low <= open)),
    CONSTRAINT chk_market_volume_nonnegative CHECK (volume IS NULL OR volume >= 0)
);

CREATE INDEX IF NOT EXISTS idx_market_observations_security_date
  ON public.market_observations(security_id, observation_date DESC);

CREATE TABLE IF NOT EXISTS public.financial_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL REFERENCES public.companies(company_id) ON DELETE CASCADE,
    event_type VARCHAR(60) NOT NULL,
    event_date DATE NOT NULL,
    title VARCHAR(300) NOT NULL,
    description TEXT,
    source_name VARCHAR(120),
    source_uri TEXT,
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_financial_event_source UNIQUE (source_uri)
);
CREATE INDEX IF NOT EXISTS idx_financial_events_company_date
  ON public.financial_events(company_id, event_date DESC);

CREATE TABLE IF NOT EXISTS public.news_articles (
    article_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER REFERENCES public.companies(company_id) ON DELETE SET NULL,
    security_id BIGINT REFERENCES public.securities(security_id) ON DELETE SET NULL,
    title VARCHAR(500) NOT NULL,
    content TEXT NOT NULL,
    source_name VARCHAR(120) NOT NULL,
    source_uri TEXT NOT NULL UNIQUE,
    published_at TIMESTAMPTZ,
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_news_entity CHECK (company_id IS NOT NULL OR security_id IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_news_company_published
  ON public.news_articles(company_id, published_at DESC);

CREATE TABLE IF NOT EXISTS public.model_predictions (
    prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    security_id BIGINT NOT NULL REFERENCES public.securities(security_id) ON DELETE CASCADE,
    prediction_type VARCHAR(40) NOT NULL,
    prediction_date DATE NOT NULL,
    target_date DATE,
    predicted_value NUMERIC(24,10),
    signal VARCHAR(30),
    model_name VARCHAR(100) NOT NULL,
    model_version VARCHAR(50) NOT NULL,
    metrics JSONB NOT NULL DEFAULT '{}'::jsonb,
    features JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_prediction_type CHECK (prediction_type IN ('ANOMALY','VOLATILITY')),
    CONSTRAINT uq_prediction_model_date UNIQUE
      (security_id, prediction_type, prediction_date, model_name, model_version)
);
CREATE INDEX IF NOT EXISTS idx_model_predictions_security_date
  ON public.model_predictions(security_id, prediction_date DESC);

COMMIT;
